    private static var lines: [String]?
    private static let lock = NSLock()

    static func valid(_ s: Int, _ a: Int) -> Bool { s >= 1 && s <= 114 && a >= 1 && a <= counts[s - 1] }

    static func surahName(_ s: Int) -> String { (1...114).contains(s) ? names[s - 1] : "" }

    /** رقم الآية في المصحف كله (٠..٦٢٣٥) */
    static func index(_ s: Int, _ a: Int) -> Int { counts.prefix(s - 1).reduce(0, +) + a - 1 }

    /** {سورة، آية} من الرقم العام */
    static func fromIndex(_ i: Int) -> (Int, Int) {
        var idx = ((i % total) + total) % total
        var s = 0
        while idx >= counts[s] { idx -= counts[s]; s += 1 }
        return (s + 1, idx + 1)
    }

    private static func load() -> [String] {
        lock.lock(); defer { lock.unlock() }
        if let l = lines { return l }
        // في التطبيق داخل مجلد quran، وفي الويدجت في جذر الحزمة
        guard let url = Bundle.main.url(forResource: "hafs", withExtension: "txt", subdirectory: "quran")
                ?? Bundle.main.url(forResource: "hafs", withExtension: "txt"),
              let text = try? String(contentsOf: url, encoding: .utf8) else { return [] }
        let l = text.components(separatedBy: "\n").map { $0.replacingOccurrences(of: "\r", with: "") }
        lines = l
        return l
    }

    /** نص الآية بالرسم العثماني (بدون رقم)؛ يُفضّل استدعاؤه أول مرة خارج الخيط الرئيسي */
    static func verse(_ s: Int, _ a: Int) -> String? {
        guard valid(s, a) else { return nil }
        let l = load()
        let i = index(s, a)
        return i < l.count ? l[i] : nil
    }

    /** النص مع علامة نهاية الآية برقمها (يرسمها خط المجمع) */
    static func withNumber(_ text: String, _ a: Int) -> String { text + "\u{00A0}" + ar(a) }

    static func juzOf(page: Int) -> Int {
        var j = 1
        for (i, start) in juzStart.enumerated() where start <= page { j = i + 1 }
        return j
    }

    /** السورة التي تبدأ بها الصفحة أو تستمر فيها */
    static func surahOf(page: Int) -> Int {
        var s = 1
        for (i, start) in surahStart.enumerated() {
            if start < page { s = i + 1 } else if start == page { s = i + 1; break }
        }
        return s
    }

    /** «سورة البقرة · الجزء ١» */
    static func whereIs(page: Int) -> String {
        L("سورة ") + surahName(surahOf(page: page)) + L(" · الجزء ") + ar(juzOf(page: page))
    }
